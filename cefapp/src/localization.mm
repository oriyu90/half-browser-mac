std::string Localization::get(const std::string& key) const {
    if (language_ == "ja") {
        const auto& ja = japaneseCatalog();
        auto it = ja.find(key);
        if (it != ja.end()) return it->second;
    }
    const auto& en = englishCatalog();
    auto it = en.find(key);
    if (it != en.end()) return it->second;
    return key;
}

std::vector<std::string> Localization::englishKeys() {
    std::vector<std::string> out;
    out.reserve(englishCatalog().size());
    for (const auto& kv : englishCatalog()) out.push_back(kv.first);
    return out;
}

std::vector<std::string> Localization::japaneseKeys() {
    std::vector<std::string> out;
    out.reserve(japaneseCatalog().size());
    for (const auto& kv : japaneseCatalog()) out.push_back(kv.first);
    return out;
}
